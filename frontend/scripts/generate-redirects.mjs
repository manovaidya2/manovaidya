import fs from "node:fs/promises";
import { canonicalPaths, canonicalPathAliases, getCanonicalUrl, normalizePath } from "../src/utils/canonical.js";
import { readContentSnapshot, getLegacyAliases } from "./seo-content.mjs";

const redirects = new Map([["/index.html", "/"]]);
const content = await readContentSnapshot();
const dynamicAliases = getLegacyAliases(content);
const dynamicRoutes = [
  ...content.blogs.map((blog) => `/blog/${blog.slug}`),
  ...content.caseStudies.map((study) => `/case-studies/${study.slug}`),
];
for (const route of [...canonicalPaths, ...Object.keys(canonicalPathAliases), ...dynamicRoutes, ...dynamicAliases.keys()]) {
  const base = normalizePath(route);
  const canonical = new URL(dynamicAliases.get(base) || getCanonicalUrl(route)).pathname;
  if (base === "/") continue;
  for (const variant of [base, `${base}/`, `${base}.html`, `${base}/index.html`]) {
    if (variant !== canonical) redirects.set(variant, canonical);
  }
}

const lines = [
  "# Generated by npm run generate:redirects; include inside nginx's http context.",
  "map_hash_bucket_size 256;",
  "map $uri $seo_redirect_path {",
  '    default "";',
  ...[...redirects].sort(([a], [b]) => a.localeCompare(b)).map(([from, to]) => `    ${from} ${to};`),
  // Dynamic detail routes added after deployment follow the same policy.
  '    ~^/(blog|case-studies)/([^/.]+)$ /$1/$2/;',
  '    ~^/(blog|case-studies)/([^/.]+)\\.html$ /$1/$2/;',
  '    ~^/(blog|case-studies)/([^/.]+)/index\\.html$ /$1/$2/;',
  "}",
  "",
];
await fs.mkdir("deploy", { recursive: true });
await fs.writeFile("deploy/canonical-redirects.map", lines.join("\n"));
console.log(`Generated Nginx redirects for ${canonicalPaths.length} static pages, ${dynamicRoutes.length} dynamic pages, and ${Object.keys(canonicalPathAliases).length + dynamicAliases.size} aliases.`);
