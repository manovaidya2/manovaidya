function RawArticleContent({ onCitationClick }) {
  const ruleKeysByLine = new Map();
  const faqAnswerRuleKeys = new Map();
  const consultationRuleKeys = new Map();
  const linkedRuleKeys = new Set();
  const extraLinkTexts = [
    ["about-doctor-1", "Founder, Manovaidya | Ayurvedacharya | Creator of the Neuro-Ayurveda Development System"],
    ["about-doctor-2", "Clinical Focus: Autism, ADHD, Child Development and Mental Health"],
    ["about-doctor-3", "Neuro-Ayurveda Development System"],
    [
      "consultation-1",
      "For any academic or developmental assistance, education difficulties, attention issues, or other learning concerns, visit Dr. Ankush Garg and the Manovaidya team for guidance. The first step is to have a detailed assessment of your child's strengths, challenges and developmental needs. [1,2]",
    ],
    [
      "consultation-2",
      "Families receive a detailed multi faceted learning assessment and tailored guidance on their child's learning and developmental profile and next steps to maximize future learning. To ensure that every child is confident, learns to their full potential and achieves the development they need, supported at the right time and place. [1,2,7]",
    ],
  ];

  bodyLines.forEach((line, index) => {
    const text = line.trimEnd();
    const trimmed = text.trim();

    if (
      !trimmed ||
      (faqStartIndex !== -1 && index >= faqStartIndex) ||
      sectionIds.has(trimmed) ||
      trimmed.endsWith("?") ||
      trimmed.startsWith("[") ||
      trimmed.startsWith("http")
    ) {
      return;
    }

    const ruleKeys = getArticleLinkRuleKeysForText(text, linkedRuleKeys);

    if (ruleKeys.size) {
      ruleKeysByLine.set(index, ruleKeys);
    }
  });

  faqs.forEach((faq) => {
    const answerRuleKeys = getArticleLinkRuleKeysForText(faq.answer, linkedRuleKeys);

    if (answerRuleKeys.size) {
      faqAnswerRuleKeys.set(faq.question, answerRuleKeys);
    }
  });

  extraLinkTexts.forEach(([key, text]) => {
    const ruleKeys = getArticleLinkRuleKeysForText(text, linkedRuleKeys);

    if (ruleKeys.size) {
      consultationRuleKeys.set(key, ruleKeys);
    }
  });

  return (
    <section className="mt-8 space-y-3 text-[14px] font-semibold leading-7 text-[#51465a]">
      {bodyLines.map((line, index) => (
        <ArticleLine
          key={`${line}-${index}`}
          line={line}
          index={index}
          onCitationClick={onCitationClick}
          allowedRuleKeys={ruleKeysByLine.get(index)}
          faqAnswerRuleKeys={faqAnswerRuleKeys}
          consultationRuleKeys={consultationRuleKeys}
        />
      ))}
    </section>
  );
}

