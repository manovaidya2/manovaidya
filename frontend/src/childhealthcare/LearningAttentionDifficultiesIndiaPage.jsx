const getArticleLinkRuleKey = (rule) => `${rule.href}|${rule.pattern.source}`;

function getArticleLinkRuleKeysForText(text, linkedRuleKeys) {
  const source = String(text);
  const ruleKeys = new Set();
  let cursor = 0;
  let safety = 0;

  while (cursor < source.length && safety < 100) {
    safety += 1;
    const remaining = source.slice(cursor);
    const candidates = [];

    articleLinkRules.forEach((rule) => {
      const ruleKey = getArticleLinkRuleKey(rule);

      if (linkedRuleKeys.has(ruleKey)) {
        return;
      }

      const match = remaining.match(rule.pattern);

      if (match) {
        candidates.push({
          index: match.index,
          length: match[0].length,
          ruleKey,
        });
      }
    });

    candidates.sort((a, b) => a.index - b.index || b.length - a.length);

    if (!candidates.length) {
      break;
    }

    const next = candidates[0];
    linkedRuleKeys.add(next.ruleKey);
    ruleKeys.add(next.ruleKey);
    cursor += next.index + next.length;
  }

  return ruleKeys;
}

function getFaqs() {
  if (faqStartIndex === -1 || consultationStartIndex === -1) {
    return [];
  }

  const lines = bodyLines.slice(faqStartIndex + 1, consultationStartIndex).map((line) => line.trim()).filter(Boolean);
  const faqs = [];
  let currentQuestion = null;
  let answerLines = [];

  lines.forEach((line) => {
    if (line.endsWith("?")) {
      if (currentQuestion) {
        faqs.push({ question: currentQuestion, answer: answerLines.join(" ") });
      }
      currentQuestion = line;
      answerLines = [];
    } else if (currentQuestion) {
      answerLines.push(line);
    }
  });

  if (currentQuestion) {
    faqs.push({ question: currentQuestion, answer: answerLines.join(" ") });
  }

  return faqs;
}

