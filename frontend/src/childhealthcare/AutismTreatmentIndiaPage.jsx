function buildRawFaqs(lines) {
  const items = [];
  let current = null;

  lines.forEach((line) => {
    const text = line.trim();

    if (!text) {
      return;
    }

    if (text.endsWith("?")) {
      if (current) {
        items.push(current);
      }
      current = { question: text, answer: [] };
      return;
    }

    if (current) {
      current.answer.push(line.trimEnd());
    }
  });

  if (current) {
    items.push(current);
  }

  return items;
}

