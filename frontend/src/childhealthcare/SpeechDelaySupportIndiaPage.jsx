function hasLinkedArticlePhrase(linkedKeywordPhrases, phrase) {
  const normalizedPhrase = normalizeArticleLinkPhrase(phrase);

  return Array.from(linkedKeywordPhrases).some(
    (linkedPhrase) => linkedPhrase === normalizedPhrase || linkedPhrase.includes(normalizedPhrase) || normalizedPhrase.includes(linkedPhrase)
  );
}

function getArticleLinkRuleKeysForText(text, linkedRuleKeys, linkedKeywordPhrases) {
  const source = String(text);
  const ruleKeys = new Set();
  let cursor = 0;
  let safety = 0;

  while (cursor < source.length && safety < 100) {
    safety += 1;
    const remaining = source.slice(cursor);
    const candidates = [];

    articleLinkRules.forEach((rule) => {
      const ruleKey = getArticleLinkRuleKey(rule);

      const match = remaining.match(rule.pattern);

      if (match) {
        if (linkedRuleKeys.has(ruleKey) || hasLinkedArticlePhrase(linkedKeywordPhrases, match[0])) {
          return;
        }

        candidates.push({
          index: match.index,
          length: match[0].length,
          text: match[0],
          ruleKey,
        });
      }
    });

    candidates.sort((a, b) => a.index - b.index || b.length - a.length);

    if (!candidates.length) {
      break;
    }

    const next = candidates[0];
    linkedRuleKeys.add(next.ruleKey);
    linkedKeywordPhrases.add(normalizeArticleLinkPhrase(next.text));
    ruleKeys.add(next.ruleKey);
    cursor += next.index + next.length;
  }

  return ruleKeys;
}

