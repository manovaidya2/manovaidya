function ArticleLine({ line, index, onCitationClick, allowedRuleKeys, faqAnswerRuleKeys }) {
  const absoluteIndex = (bodyStartIndex === -1 ? 0 : bodyStartIndex) + index;
  const text = line.trimEnd();
  const trimmed = text.trim();

  if (faqStartIndex !== -1 && absoluteIndex > faqStartIndex && absoluteIndex < referencesStartIndex) return null;
  if (referencesStartIndex !== -1 && absoluteIndex >= referencesStartIndex) return null;
  if (/^_+$/.test(trimmed)) return null;
  if (!trimmed) return <div key={`empty-${index}`} className="h-2" aria-hidden="true" />;

  if (trimmed === "FAQs") {
    return (
      <section key={trimmed} id="frequently-asked-questions" className="scroll-mt-28 pt-5">
        <h2 className="text-[22px] font-black leading-tight text-[#17111f]">FAQs</h2>
        <div className="mt-4 overflow-hidden rounded-lg border border-[#eadff1] bg-white">
          {faqs.map((faq, faqIndex) => (
            <details key={faq.question} open={faqIndex === 0} className="border-b border-[#eadff1] last:border-b-0">
              <summary className="flex cursor-pointer list-none items-center justify-between gap-4 px-4 py-3 text-left text-[13px] font-black text-[#21142d]">
                {faq.question}
                <ChevronDown className="h-4 w-4 shrink-0 text-[#7835A4]" />
              </summary>
              <p className="px-4 pb-4 text-[12.5px] font-semibold leading-6 text-[#5f5367]">
                <ArticleLinkedText text={faq.answer} onCitationClick={onCitationClick} allowedRuleKeys={faqAnswerRuleKeys?.get(faq.question)} />
              </p>
            </details>
          ))}
        </div>
      </section>
    );
  }

  if (trimmed === "Book a Consultation") return null;

  const sectionId = sectionHeadingMap.get(trimmed);
  const isQuestion = trimmed.endsWith("?");
  const isSubheading = !sectionId && !isQuestion && trimmed.length < 90 && !trimmed.startsWith("[") && !trimmed.startsWith("http") && !/[.!]$/.test(trimmed);

  if (sectionId || isQuestion) {
    const headingId = sectionId || slugifyHeading(trimmed);
    return (
      <h2 key={`${trimmed}-${index}`} id={headingId} className="scroll-mt-28 pt-5 text-[20px] font-black leading-tight text-[#17111f]" style={{ whiteSpace: "pre-wrap" }}>
        <ArticleLinkedText text={trimmed} onCitationClick={onCitationClick} />
      </h2>
    );
  }

  if (isSubheading) {
    return (
      <h3 key={`${trimmed}-${index}`} className="pt-3 text-[15px] font-black leading-6 text-[#5d268d]" style={{ whiteSpace: "pre-wrap" }}>
        <ArticleLinkedText text={text} onCitationClick={onCitationClick} allowedRuleKeys={allowedRuleKeys} />
      </h3>
    );
  }

  return (
    <p key={`${trimmed}-${index}`} className="text-[14px] font-semibold leading-7 text-[#51465a]" style={{ whiteSpace: "pre-wrap" }}>
      <ArticleLinkedText text={text} onCitationClick={onCitationClick} allowedRuleKeys={allowedRuleKeys} />
    </p>
  );
}

function RawArticleContent({ onCitationClick }) {
  const ruleKeysByLine = new Map();
  const faqAnswerRuleKeys = new Map();
  const linkedRuleKeys = new Set();

  bodyLines.forEach((line, index) => {
    const absoluteIndex = (bodyStartIndex === -1 ? 0 : bodyStartIndex) + index;
    const trimmed = line.trim();

    if (
      !trimmed ||
      (faqStartIndex !== -1 && absoluteIndex > faqStartIndex && absoluteIndex < referencesStartIndex) ||
      (referencesStartIndex !== -1 && absoluteIndex >= referencesStartIndex) ||
      /^_+$/.test(trimmed) ||
      sectionHeadingMap.has(trimmed) ||
      trimmed.endsWith("?") ||
      trimmed.startsWith("[") ||
      trimmed.startsWith("http")
    ) {
      return;
    }

    const ruleKeys = getArticleLinkRuleKeysForText(line, linkedRuleKeys);

    if (ruleKeys.size) {
      ruleKeysByLine.set(index, ruleKeys);
    }
  });

  faqs.forEach((faq) => {
    const answerRuleKeys = getArticleLinkRuleKeysForText(faq.answer, linkedRuleKeys);

    if (answerRuleKeys.size) {
      faqAnswerRuleKeys.set(faq.question, answerRuleKeys);
    }
  });

  return (
    <section className="mt-8 space-y-3 text-[14px] font-semibold leading-7 text-[#51465a]">
      {bodyLines.map((line, index) => (
        <ArticleLine
          key={`${line}-${index}`}
          line={line}
          index={index}
          onCitationClick={onCitationClick}
          allowedRuleKeys={ruleKeysByLine.get(index)}
          faqAnswerRuleKeys={faqAnswerRuleKeys}
        />
      ))}
    </section>
  );
}

